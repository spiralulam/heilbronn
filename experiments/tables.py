"""Build the LaTeX tables of the revision from out/results/*.json.

No number in the computational section is typed by hand: every table is
generated here. Output: out/tables/*.tex (and a plain-text summary on stdout).
"""
import json
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "out" / "results"
TAB = HERE / "out" / "tables"
STATUS = {2: "opt", 9: "limit", 11: "interrupted"}


def load():
    rows = []
    for f in sorted(RES.glob("*.json")):
        r = json.loads(f.read_text())
        if r.get("finished"):
            rows.append(r)
    return rows


def fmt_t(r):
    t = r["runtime"]
    s = f"{t:,.1f}" if t < 100 else f"{t:,.0f}"
    return s if r["status"] == 2 else rf"$>${s}"


def gap(r):
    if r["objval"] is None or r["objbound"] is None:
        return "--"
    return f"{(r['objbound'] - r['objval']) / max(abs(r['objval']), 1e-12):.1e}"


def write(name, header, lines, caption):
    TAB.mkdir(parents=True, exist_ok=True)
    body = "\n".join(lines)
    tex = (f"% generated by tables.py\n\\begin{{tabular}}{{{header[0]}}}\n\\toprule\n{header[1]} \\\\\n"
           f"\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n% {caption}\n")
    (TAB / f"{name}.tex").write_text(tex)
    print(f"== {name}\n{tex}")


def main():
    rows = load()
    by = lambda **kw: [r for r in rows if all(r["spec"].get(k) == v for k, v in kw.items())]

    # A: main results, median and range over seeds
    lines = []
    for n in range(5, 10):
        rs = by(block="A", n=n)
        if not rs:
            continue
        ts = [r["runtime"] for r in rs]
        best = max(rs, key=lambda r: r["objval"] or 0)
        lines.append(f"{n} & {st.median(ts):,.1f} & {min(ts):,.1f}--{max(ts):,.1f} & "
                     f"{int(st.median(r['nodecount'] for r in rs)):,} & {best['objval']:.7f} & "
                     f"{best['objbound']:.7f} & {gap(best)} & {best.get('constr_vio', 0):.1e} \\\\")
    write("main", ("r r r r r r r r", r"$n$ & median [s] & range [s] & nodes & objective & dual bound & rel.\ gap & max viol."),
          lines, "block A, 5 seeds")

    # B: case models
    lines = []
    for n in range(5, 10):
        cells = []
        for v in ("type2", "type3"):
            rs = by(block="B", n=n, variant=v)
            cells += [f"{rs[0]['objbound']:.7f} & {fmt_t(rs[0])}"] if rs else ["-- & --"]
        lines.append(f"{n} & " + " & ".join(cells) + " \\\\")
    write("cases", ("r r r r r", r"$n$ & bound II & time II [s] & bound III & time III [s]"),
          lines, "block B")

    # C, D, E, F: runtimes per variant
    cols = [("A", {}, False, "full $P^\\star_\\Delta$ (seed 0)"),
            ("D", {"nobound": True}, False, "no boundary pattern"),
            ("D", {"signfix": False}, False, "no sign fixing"),
            ("D", {"order": False}, False, "no interior order"),
            ("D", {"wsub": False}, False, "no substitution"),
            ("D", {"cap": False}, False, r"no $z\le\Delta_{n-1}$"),
            ("D", {"freebin": True}, False, "fixed signs w/o binaries"),
            ("D", {"strips": True}, False, "with strip capacities"),
            ("D", {"contacts": True}, False, "with contact conditions"),
            ("E", {}, True, "warm start"),
            ("F", {}, False, "Gurobi 11.0.1")]
    lines = []
    for blk, opts, ws, name in cols:
        cells = []
        for n in (7, 8, 9):
            rs = [r for r in rows if r["spec"]["block"] == blk and r["spec"]["n"] == n
                  and r["spec"]["opts"] == opts and r["spec"]["warmstart"] == ws
                  and r["spec"]["seed"] == 0 and r["spec"]["variant"] == "full"]
            cells.append(fmt_t(rs[0]) if rs else "--")
        lines.append(f"{name} & " + " & ".join(cells) + " \\\\")
    base = {r["spec"]["n"]: r for r in by(block="C")}
    lines.append("baseline $P^0_\\Delta$ & " + " & ".join(fmt_t(base[n]) if n in base else "--" for n in (7, 8, 9)) + " \\\\")
    write("ablation", ("l r r r", r"variant & $n=7$ [s] & $n=8$ [s] & $n=9$ [s]"), lines,
          "blocks A (seed 0), C, D, E, F; $>$ marks the 4 h limit")

    # C separately for n=5..7
    lines = [f"{n} & {fmt_t(base[n])} & {gap(base[n])} \\\\" for n in (5, 6, 7) if n in base]
    write("baseline", ("r r r", r"$n$ & time [s] & rel.\ gap"), lines, "block C")

    # G: n = 10
    rs = by(block="G")
    if rs:
        r = rs[0]
        write("n10", ("r r r r", r"time [s] & objective & dual bound & rel.\ gap"),
              [f"{fmt_t(r)} & {r['objval']:.7f} & {r['objbound']:.7f} & {gap(r)} \\\\"], "block G")

    # machine and solver, for Section 5.1
    if rows:
        r0 = rows[0]
        print("machine:", json.dumps(r0["machine"]), "| gurobi", r0["gurobi_version"],
              "| threads used", r0.get("threads_used"), "| params", json.dumps(r0["params"]))


if __name__ == "__main__":
    main()
